CREATE TABLE IF NOT EXISTS financial_event_outbox (
    event_id VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
    topic VARCHAR(255) NOT NULL,
    event_key VARCHAR(255) NULL,
    body TEXT NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    available_at DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    attempts BIGINT NOT NULL DEFAULT 0,
    lease_token CHAR(36) NULL,
    lease_until DATETIME(6) NULL,
    delivered_at DATETIME(6) NULL,
    last_error VARCHAR(255) NULL,
    PRIMARY KEY (event_id),
    KEY idx_outbox_pending (delivered_at,available_at,lease_until,event_id),
    KEY idx_outbox_delivered (delivered_at,event_id),
    CHECK (attempts >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS pocket_balance_records (
    pocket_id VARCHAR(255) NOT NULL,
    pocket_version BIGINT NOT NULL,
    balance_after DECIMAL(40,20) NOT NULL,
    wallet_id VARCHAR(255) NOT NULL,
    currency_id VARCHAR(255) NOT NULL,
    player_id BIGINT NOT NULL,
    currency_code VARCHAR(255) NOT NULL,
    currency_sysname VARCHAR(255) NOT NULL,
    wallet_sys_name VARCHAR(255) NOT NULL,
    wallet_kind VARCHAR(64) NOT NULL,
    source_service VARCHAR(64) NOT NULL,
    operation VARCHAR(64) NOT NULL,
    tracking_id VARCHAR(255) NULL,
    company_id VARCHAR(255) NULL,
    brand_id VARCHAR(255) NULL,
    source_business_occurred_at DATETIME(6) NULL,
    movement_context VARCHAR(64) NULL,
    recorded_at DATETIME(6) NOT NULL,
    event_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (pocket_id,pocket_version),
    UNIQUE KEY uq_balance_event (event_id),
    KEY idx_balance_recorded (recorded_at,pocket_id,pocket_version),
    CHECK (pocket_version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS financial_outcomes (
    source_service VARCHAR(64) NOT NULL,
    tracking_id VARCHAR(255) NOT NULL,
    operation VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    direction VARCHAR(8) NOT NULL,
    amount DECIMAL(40,20) NOT NULL,
    currency_id VARCHAR(255) NOT NULL,
    currency_code VARCHAR(255) NOT NULL,
    currency_sysname VARCHAR(255) NULL,
    player_id BIGINT NOT NULL,
    pocket_id VARCHAR(255) NULL,
    wallet_id VARCHAR(255) NULL,
    wallet_sys_name VARCHAR(255) NULL,
    pocket_version BIGINT NULL,
    partner_id VARCHAR(255) NULL,
    partner_reference_id VARCHAR(255) NULL,
    failure_reason VARCHAR(255) NULL,
    company_id VARCHAR(255) NULL,
    brand_id VARCHAR(255) NULL,
    source_business_occurred_at DATETIME(6) NULL,
    movement_context VARCHAR(64) NULL,
    recorded_at DATETIME(6) NOT NULL,
    event_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (source_service,tracking_id,operation),
    UNIQUE KEY uq_outcome_event (event_id),
    KEY idx_outcome_cohort (source_business_occurred_at,movement_context,source_service),
    KEY idx_outcome_recorded (recorded_at,source_service,tracking_id,operation),
    CHECK (status IN ('committed','rejected')),
    CHECK (direction IN ('debit','credit')),
    CHECK (amount >= 0),
    CHECK (pocket_version IS NULL OR pocket_version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
